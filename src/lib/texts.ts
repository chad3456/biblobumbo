/** Splits text into reader "pages" of roughly `size` characters on paragraph/sentence boundaries. */
export function paginate(text: string, size = 1100): string[] {
  const paras = text.replace(/\r\n/g, '\n').split(/\n\s*\n/).map((p) => p.trim()).filter(Boolean)
  const pages: string[] = []
  let cur = ''
  const push = () => {
    if (cur.trim()) pages.push(cur.trim())
    cur = ''
  }
  for (const p of paras) {
    if (p.length > size) {
      push()
      const sentences = p.match(/[^.!?]+[.!?]+["')\]]*\s*|[^.!?]+$/g) ?? [p]
      for (const s of sentences) {
        if (cur.length + s.length > size) push()
        cur += s
      }
      push()
      continue
    }
    if (cur.length + p.length + 2 > size) push()
    cur += (cur ? '\n\n' : '') + p
  }
  push()
  return pages.length ? pages : ['(this book is empty, it’s giving blank page)']
}
